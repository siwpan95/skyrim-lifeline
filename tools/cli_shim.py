#!/usr/bin/env python
# -*- coding: utf-8 -*-
"""霜语 · Windows 命令提示符垫片生成 / 安装 / 卸载。

被 tools/frostwords_cli.py 的 install-cli / uninstall-cli 调用；
CLI 本体只做参数编排，不重复实现这些逻辑。

铁律（来自本机 win-cmd-cli-entry 的实测经验）：
    · .cmd 必须 **纯 ASCII + CRLF**。cmd.exe 按当前代码页（中文机 GBK）
      逐行解析，UTF-8 中文会让行首 ASCII 语法被吃掉，报一堆命令碎片。
    · 写字用 encoding="ascii" + newline=""，行尾由字符串自己给 "\\r\\n"。
      若再传 newline="\\r\\n" 会二次翻译，落成 CR CR LF（孤立 CR）。
    · 解释器一律加引号；py -3 不能整体加引号，所以拆成 FW_PY / FW_PYARG。
    · FW_ROOT 统一带尾部分隔符，两种 root 形式共用同一份脚本体。
"""

from __future__ import annotations

import os
import re
import sys
import winreg
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
CLI_REL = "tools\\frostwords_cli.py"
MARKER = "FW_CLI_SHIM v1"
NAMES = ("frostwords.cmd", "fwcli.cmd")


def shim_body(root_line: str) -> str:
    """生成一份 .cmd 内容。只有 root 赋值行随安装位置变化。"""
    baked = sys.executable
    lines = [
        "@echo off",
        f"rem {MARKER} - generated by tools/cli_shim.py; safe to delete.",
        "setlocal",
        root_line,
        f'set "CLI_TARGET={CLI_REL}"',
        f'set "FW_BAKED={baked}"',
        'set "FW_PY="',
        'set "FW_PYARG="',
        'if defined FW_PYTHON set "FW_PY=%FW_PYTHON%"',
        'if defined FW_PY if not exist "%FW_PY%" set "FW_PY="',
        "if defined FW_PY goto fw_run",
        'if exist "%FW_BAKED%" set "FW_PY=%FW_BAKED%"',
        "if defined FW_PY goto fw_run",
        "where py >nul 2>nul",
        'if not errorlevel 1 set "FW_PY=py"',
        "if defined FW_PY goto fw_run",
        "where python >nul 2>nul",
        'if not errorlevel 1 set "FW_PY=python"',
        "if not defined FW_PY (",
        "  echo [ERR] Python not found. Set FW_PYTHON to a python.exe path. 1>&2",
        "  exit /b 6",
        ")",
        ":fw_run",
        'if /i "%FW_PY%"=="py" set "FW_PYARG=-3"',
        '"%FW_PY%" %FW_PYARG% "%FW_ROOT%%CLI_TARGET%" %*',
        'set "FW_RC=%ERRORLEVEL%"',
        "exit /b %FW_RC%",
    ]
    return "\r\n".join(lines) + "\r\n"


def write_shim(path: Path, root_line: str) -> None:
    """纯 ASCII + CRLF 落盘。"""
    body = shim_body(root_line)
    body.encode("ascii")          # 有任何非 ASCII 字节就在这里炸掉
    with open(path, "w", encoding="ascii", newline="") as fh:
        fh.write(body)


def root_line_for(directory: Path) -> str:
    """绝对路径形式，末尾固定带一个反斜杠。"""
    return 'set "FW_ROOT=' + str(directory).rstrip("\\") + '\\"'


def write_root_shims() -> list[Path]:
    """仓库根垫片：FW_ROOT=%~dp0，clone / 搬走都不失效。"""
    out = []
    for name in NAMES:
        p = ROOT / name
        write_shim(p, 'set "FW_ROOT=%~dp0"')
        out.append(p)
    return out


def in_path(directory: Path) -> bool:
    target = os.path.normcase(os.path.abspath(str(directory)))
    for part in os.environ.get("PATH", "").split(os.pathsep):
        if part and os.path.normcase(os.path.abspath(part)) == target:
            return True
    return False


def default_shim_dir() -> tuple[Path, bool]:
    """返回 (目录, 是否已在 PATH)。

    优先级：FW_BIN_DIR → <Python 前缀>\\Scripts（本机实测就在 PATH）
    → %LOCALAPPDATA%\\frostwords\\bin。
    """
    env = os.environ.get("FW_BIN_DIR")
    if env:
        d = Path(env)
        return d, in_path(d)
    scripts = Path(sys.prefix) / "Scripts"
    if in_path(scripts):
        return scripts, True
    base = os.environ.get("LOCALAPPDATA") or str(Path.home())
    local = Path(base) / "frostwords" / "bin"
    return local, in_path(local)


def user_path() -> str:
    try:
        with winreg.OpenKey(winreg.HKEY_CURRENT_USER, "Environment") as key:
            return winreg.QueryValueEx(key, "PATH")[0]
    except OSError:
        return ""


def add_to_user_path(directory: Path) -> bool:
    """用 winreg 追加用户 PATH（不用 setx：会截断 1024 字符）。"""
    target = str(directory)
    current = user_path()
    norm = os.path.normcase(os.path.abspath(target))
    if any(os.path.normcase(os.path.abspath(p)) == norm
           for p in current.split(os.pathsep) if p):
        return False
    merged = f"{current};{target}" if current else target
    with winreg.CreateKey(winreg.HKEY_CURRENT_USER, "Environment") as key:
        winreg.SetValueEx(key, "PATH", 0, winreg.REG_EXPAND_SZ, merged)
    return True


def install(shim_dir: Path | None = None, dry_run: bool = False,
            modify_path: bool = False) -> dict:
    """生成 PATH 垫片 + 确保仓库根垫片存在。"""
    chosen, on_path = ((shim_dir, in_path(shim_dir))
                       if shim_dir else default_shim_dir())
    line = root_line_for(ROOT)

    if dry_run:
        return {
            "ok": True, "shim_dir": str(chosen), "on_path": on_path,
            "dry_run": True,
            "actions": [f"would write {ROOT / n}" for n in NAMES]
                       + [f"would write {chosen / n}" for n in NAMES],
        }

    write_root_shims()
    chosen.mkdir(parents=True, exist_ok=True)
    files = []
    for name in NAMES:
        write_shim(chosen / name, line)
        files.append(str(chosen / name))

    added = False
    if modify_path and not on_path:
        added = add_to_user_path(chosen)
        on_path = on_path or added
    return {
        "ok": True, "shim_dir": str(chosen), "on_path": on_path,
        "root_shims": [str(ROOT / n) for n in NAMES],
        "files": files, "path_modified": added, "dry_run": False,
    }


def uninstall(shim_dir: Path | None = None, dry_run: bool = False) -> dict:
    """只删含本工具标记的文件；同名手工文件跳过并列出。"""
    chosen = shim_dir or Path(default_shim_dir()[0])
    removed, skipped = [], []
    for name in NAMES:
        p = chosen / name
        if not p.exists():
            continue
        head = p.read_bytes()[:4096]
        if MARKER.encode("ascii") not in head:
            skipped.append(str(p))
            continue
        if dry_run:
            removed.append(f"would remove {p}")
        else:
            p.unlink()
            removed.append(str(p))
    return {"ok": True, "shim_dir": str(chosen),
            "removed": removed, "skipped": skipped, "dry_run": dry_run}


def inspect_shim(path: Path) -> dict:
    """字节级自检：非 ASCII / 裸 LF / 孤立 CR / 调用行引号。"""
    raw = path.read_bytes()
    body = raw.decode("ascii")
    bare_lf = body.count("\n") - body.count("\r\n")
    lone_cr = len(re.findall(r"\r(?!\n)", body))
    # 调用行形如 "%FW_PY%" ... "%FW_ROOT%%CLI_TARGET%" %*
    # （路径已抽成 %CLI_TARGET%，所以不能按 frostwords_cli.py 字面量找）
    call_line = [ln for ln in body.splitlines()
                 if "%FW_ROOT%%CLI_TARGET%" in ln]
    quoted = (bool(call_line)
              and '"%FW_PY%"' in call_line[0]
              and 'set "CLI_TARGET=tools\\frostwords_cli.py"' in body)
    return {"path": str(path), "ascii": True, "bare_lf": bare_lf,
            "lone_cr": lone_cr, "quoted_call": quoted,
            "marker": MARKER in body, "bytes": len(raw)}
